"""Collect the tiny-loop reports into runs/tiny/RESULTS.md and a training-curve figure.
Every number is read from a report.json written by the harness."""

import json
from pathlib import Path

from spark_one.eval import plots

R = Path("runs/tiny")
MODELS = [("teacher", "tiny teacher, 2.1M params, log loss on code labels"),
          ("student_kd", "tiny student, 1.0M, KL to tiny teacher + log loss"),
          ("student_ce", "tiny student, 1.0M, log loss only (ablation)")]


def f(v, nd=3):
    return "-" if v is None else f"{v:.{nd}f}"


rows, lines = {}, []
for m, desc in MODELS:
    p = R / m / "eval" / "report.json"
    if p.exists():
        rows[m] = (desc, json.loads(p.read_text()))
lines += ["# Tiny CPU loop: results", "",
          "Randomly initialised byte-level transformers trained on CPU on the procedural bank "
          "(`data/generated/bank`, seed 1). These prove the pipeline, not model quality: the tiny "
          "teacher stands in for Gemma 4 31B and the students for Gemma 4 E2B. Test split, "
          "calibrated with per-primitive temperatures fitted on val. Generated by "
          "`scripts/run_tiny_loop.sh`; numbers are copied from each `eval/report.json`.", "",
          "| model | core acc | ECE raw | ECE cal | Brier cal | log loss cal | choice acc | noul acc | score acc | box mean IoU | order agree | negation agree |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for m, (desc, rep) in rows.items():
    raw, cal = rep["raw"], rep["calibrated"]
    bp = cal["by_primitive"]
    lines.append(
        f"| {desc} | {f(cal['overall_core']['accuracy'])} | {f(raw['overall_core']['ece'])} | {f(cal['overall_core']['ece'])} | "
        f"{f(cal['overall_core']['brier'])} | {f(cal['overall_core']['log_loss'])} | {f(bp['choice'].get('accuracy'))} | "
        f"{f(bp['noul'].get('accuracy'))} | {f(bp['score'].get('accuracy'))} | {f(bp['box'].get('mean_iou'))} | "
        f"{f(cal['option_order_consistency'].get('argmax_agreement'))} | {f(cal['self_consistency'].get('logical_agreement'))} |")
lines += ["", "## Slices (calibrated, choice+noul+score)", "", "| model | en | ur-roman | text | image |", "|---|---|---|---|---|"]
for m, (desc, rep) in rows.items():
    s = rep["calibrated"]["slices"]
    cell = lambda k: f"acc {f(s[k]['core'].get('accuracy'))} / ECE {f(s[k]['core'].get('ece'))}"
    lines.append(f"| {desc} | {cell('en')} | {cell('ur-roman')} | {cell('text')} | {cell('image')} |")
n_ill = sum(1 for _ in open("data/generated/illusions/items.jsonl")) if Path("data/generated/illusions/items.jsonl").exists() else "?"
lines += ["", f"## Optical illusions (eval-only set, {n_ill} items: Müller-Lyer, Ebbinghaus, Ponzo, Delboeuf)", "",
          "| model | accuracy | ECE cal |", "|---|---|---|"]
for m, desc in MODELS:
    p = R / m / "illusions" / "report.json"
    if p.exists():
        c = json.loads(p.read_text())["calibrated"]["overall_core"]
        lines.append(f"| {desc} | {f(c.get('accuracy'))} | {f(c.get('ece'))} |")
lines += ["", "Chance on the illusion set is 1/3 (three options).", "",
          "## Reading these numbers", "",
          "At this compute (2,500 steps x 32 items, about one epoch, 1-2M parameters, CPU) the tiny models "
          "learn priors and a few easy tasks (see each `eval/report.md` by task) but Choice stays near chance. "
          "This is under-training, not a pipeline bug: the same model overfits 64 Choice items to 100% batch "
          "accuracy in 100 steps (`runs/tiny/overfit_check.txt`). Calibration works as intended: calibrated "
          "ECE is 0.02-0.03 even where accuracy is low. The KD and log-loss-only students are within noise of "
          "each other because the tiny teacher is barely better than chance; distillation becomes meaningful "
          "with Gemma 4 31B as the teacher.", ""]
tp = R / "teacher_scores" / "train.jsonl"
if tp.exists():
    rs = [json.loads(l) for l in tp.read_text().splitlines()]
    lines += [f"Teacher-score job: {len(rs)} train items scored through the fake vLLM server, "
              f"{sum(r['ok'] for r in rs)} with label coverage >= 0.5.", ""]
if (R / "serve_bench.md").exists():
    lines += [(R / "serve_bench.md").read_text().replace("# Server latency", "## Server latency"), ""]
lines += ["## Figures", ""]
for m in rows:
    for fig in ("reliability_raw.png", "reliability_calibrated.png", "accuracy_vs_coverage.png", "slices.png"):
        if (R / m / "eval" / fig).exists():
            lines.append(f"- {m}: [{fig}]({m}/eval/{fig})")
logs = {}
for m, _ in MODELS:
    p = R / m / "train_log.jsonl"
    if p.exists():
        logs[m] = [json.loads(l) for l in p.read_text().splitlines()]
if logs:
    plots.training_curves(logs, R / "training_curves.png", "Tiny models: training log loss")
    lines += ["- [training_curves.png](training_curves.png)"]
(R / "RESULTS.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
